// ---- Small helpers
function isVideo(src = "") { return /\.mp4($|\?)/i.test(src); }

function createMediaEl(src, alt) {
  if (isVideo(src)) {
    const v = document.createElement('video');
    v.src = src;
    v.controls = true;
    v.playsInline = true;
    v.preload = 'metadata';
    v.style.maxWidth = '280px';
    v.style.maxHeight = '500px';
    v.style.borderRadius = '8px';
    return v;
  }
  const img = document.createElement('img');
  img.src = src;
  img.alt = alt || '';
  img.loading = 'lazy';
  img.decoding = 'async';
  img.fetchPriority = 'low';
  img.onerror = () => {
    if (!img.dataset.fallbackTried && /\.webp($|\?)/i.test(img.src)) {
      img.dataset.fallbackTried = 'true';
      img.src = src.replace(/\.webp($|\?)/i, '.jpg$1');
      return;
    }
    img.remove();
  };
  return img;
}

// Normalize/resolve a display name for a Feature from different datasets
function featureName(props = {}) {
  return (
    props.name ||
    props.ADMIN ||
    props.NAME ||
    props.Country ||
    props.country ||
    props.admin ||
    props.sovereignt ||
    props.SOVEREIGNT ||
    props.sov_a3 ||
    ''
  );
}

